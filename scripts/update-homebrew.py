#!/usr/bin/env python3
"""Generate the tap formula from the latest stable, checksum-verified release."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile


REPOSITORY = "CCH-HQ/cchp-cli"
PLATFORMS = ("darwin_arm64", "darwin_amd64", "linux_arm64", "linux_amd64")


def gh(*args):
    return subprocess.check_output(["gh", *args], text=True)


def render_formula(tag, checksums):
    if not re.fullmatch(r"v(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)", tag):
        raise ValueError("Homebrew requires a stable vMAJOR.MINOR.PATCH tag")
    version = tag[1:]
    blocks = []
    for os_name, brew_os in (("darwin", "macos"), ("linux", "linux")):
        blocks.append(f"  on_{brew_os} do")
        for arch, brew_arch in (("arm64", "arm"), ("amd64", "intel")):
            filename = f"cchp_{version}_{os_name}_{arch}.tar.gz"
            checksum = checksums[filename]
            if not re.fullmatch(r"[0-9a-f]{64}", checksum):
                raise ValueError(f"Invalid SHA256 for {filename}")
            blocks.extend([
                f"    on_{brew_arch} do",
                f'      url "https://github.com/{REPOSITORY}/releases/download/{tag}/{filename}"',
                f'      sha256 "{checksum}"',
                "    end",
            ])
        blocks.extend(["  end", ""])
    return f'''# Generated by cchp-cli/scripts/update-homebrew.py. Do not edit.
class Cchp < Formula
  desc "Command-line tool for CCHP (Claude Code Hub Plus)"
  homepage "https://github.com/{REPOSITORY}"
  license "MIT"

{chr(10).join(blocks)}
  def install
    bin.install "cchp"
    generate_completions_from_executable(bin/"cchp", "completion")
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/cchp --version")
    assert_match "getUsageSummary", shell_output("#{{bin}}/cchp commands --search getUsageSummary --json")
  end
end
'''


def update(tag, output):
    # Validate before passing the tag to gh or using it in an asset filename.
    version_match = re.fullmatch(r"v(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)", tag)
    if not version_match:
        raise ValueError("Homebrew requires a stable vMAJOR.MINOR.PATCH tag")
    release = json.loads(gh("release", "view", tag, "--repo", REPOSITORY,
                            "--json", "tagName,isDraft,isPrerelease"))
    if release["isDraft"] or release["isPrerelease"]:
        raise ValueError("Homebrew only publishes stable, public releases")
    latest = gh("release", "view", "--repo", REPOSITORY,
                "--json", "tagName", "--jq", ".tagName").strip()
    if release["tagName"] != tag or latest != tag:
        raise ValueError(f"Refusing to replace the latest stable release ({latest}) with {tag}")

    with tempfile.TemporaryDirectory(prefix="cchp-homebrew-") as directory:
        paths = Path(directory)
        filenames = [f"cchp_{tag[1:]}_{platform}.tar.gz" for platform in PLATFORMS]
        download_args = ["release", "download", tag, "--repo", REPOSITORY,
                         "--dir", directory, "--pattern", "checksums.txt"]
        for filename in filenames:
            download_args.extend(["--pattern", filename])
        gh(*download_args)
        checksums = {}
        for line in (paths / "checksums.txt").read_text().splitlines():
            checksum, filename = line.split()
            if filename in checksums:
                raise ValueError(f"Duplicate checksum for {filename}")
            checksums[filename] = checksum
        for filename in filenames:
            with (paths / filename).open("rb") as archive:
                actual = hashlib.file_digest(archive, "sha256").hexdigest()
            if actual != checksums[filename]:
                raise ValueError(f"SHA256 mismatch for {filename}")
        formula = render_formula(tag, checksums)

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(formula)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tag", help="Stable release tag, for example v0.1.0")
    parser.add_argument("--output", type=Path, default=Path("Formula/cchp.rb"))
    args = parser.parse_args()
    update(args.tag, args.output)


if __name__ == "__main__":
    main()
